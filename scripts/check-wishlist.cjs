const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const context = {};
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../wishlist.js'), 'utf8'), context);
const { createStore, key } = context.BadRosesWishlist;
const data = new Map();
const storage = { getItem: key => data.get(key) ?? null, setItem: (key, value) => data.set(key, value) };
const first = createStore(storage);
assert.equal(first.toggle('horse-14'), true);
assert.equal(first.toggle('horse-29'), true);
assert.equal(first.toggle('item-687'), true);
const reloaded = createStore(storage);
assert.equal(reloaded.has('horse-14'), true);
assert.equal(reloaded.has('horse-29'), true);
assert.equal(reloaded.has('item-687'), true);
assert.equal(reloaded.toggle('horse-14'), false);
assert.equal(createStore(storage).has('horse-14'), false);
assert.equal(createStore(storage).has('horse-29'), true);
assert.equal(reloaded.toggle('invalid'), false);
assert.equal(JSON.parse(data.get(key)).length, 2);
reloaded.sync('["item-1550","item-1550",null,123,"invalid"]');
assert.equal(reloaded.has('item-1550'), true);
assert.equal(reloaded.has('horse-29'), false);
reloaded.sync('broken JSON');
assert.equal(reloaded.has('item-1550'), true);
reloaded.sync(null);
assert.equal(reloaded.has('item-1550'), false);
const blocked = createStore({ getItem() { throw Error('blocked'); }, setItem() { throw Error('blocked'); } });
assert.equal(blocked.persistent, false);
assert.equal(blocked.toggle('item-687'), true);
assert.equal(blocked.has('item-687'), true);
assert.equal(blocked.persistent, false);
const quota = createStore({ getItem: () => '["horse-14"]', setItem() { throw Error('quota'); } });
quota.toggle('horse-29');
assert.equal(quota.has('horse-14'), true);
assert.equal(quota.has('horse-29'), true);
assert.equal(quota.persistent, false);
const corrupt = createStore({ getItem: () => '{broken', setItem: storage.setItem });
assert.equal(corrupt.persistent, false);
corrupt.toggle('item-687');
assert.equal(corrupt.persistent, true);
console.log('Wishlist checks passed: reloads, exact variants, removal, cross-tab updates, malformed data and unavailable storage.');
